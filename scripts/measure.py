"""Measure the numbers shown on the landing page and write frontend/src/landing/measured.ts.

    python scripts/measure.py

Runs offline (fixture PayPal, rule-based agents) so the numbers are reproducible:
  * how many automated tests pass,
  * how many of the scripted red-team attacks the policy engine blocks,
  * how many rules are checked on an ordinary cart,
  * how many distinct PayPal REST endpoints the code calls.
"""

from __future__ import annotations

import asyncio
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.update({"LEASH_DATA_DIR": tempfile.mkdtemp(prefix="leash-measure-"), "LEASH_PAYPAL_MODE": "fixture", "LEASH_OFFLINE": "1"})

from leash.agent import SCENARIOS  # noqa: E402
from leash.app import build_leash  # noqa: E402
from leash.compiler import SAMPLES  # noqa: E402


async def red_team() -> tuple[int, int, int]:
    l = build_leash()
    m = await l.compile(SAMPLES["coffee"])
    m = await l.sign(m.id)
    m = await l.fund(m.id)
    l.paypal.approve_order(m.envelope.order_id)
    await l.on_paypal_return("allowance", m.id)
    first = await l.run_agent(m.id, "a 1 kg bag of medium roast whole beans")
    names = list(SCENARIOS) + ["replay"]
    blocked = 0
    for n in names:
        p = await l.run_scenario(m.id, n)
        blocked += p.status == "blocked"
    return blocked, len(names), len(first.decision.checks)


def tests_passed() -> int:
    out = subprocess.run([sys.executable, "-m", "pytest", "tests", "-o", "addopts=", "-q"], cwd=ROOT, capture_output=True, text=True)
    m = re.search(r"(\d+) passed", out.stdout)
    if out.returncode != 0 or not m:
        raise SystemExit("tests failed; not writing numbers:\n" + out.stdout[-2000:])
    return int(m.group(1))


def paypal_endpoints() -> int:
    src = (ROOT / "leash" / "paypal" / "client.py").read_text(encoding="utf-8")
    calls = set(re.findall(r'_request\("(GET|POST)", f?"([^"?]+)', src))
    return len(calls) + 1  # + the OAuth token call


def main() -> None:
    blocked, attacks, rules = asyncio.run(red_team())
    n_tests = tests_passed()
    endpoints = paypal_endpoints()
    ts = f"""// Generated by scripts/measure.py. Do not edit by hand; re-run the script.
import {{ createElement }} from "react";
import {{ FlaskConical, Landmark, ListChecks, ShieldCheck }} from "lucide-react";

export const MEASURED = [
  {{ icon: createElement(FlaskConical), label: "Automated tests", value: "{n_tests}", delta: "passing", tone: "pos" as const, hint: "pytest, offline, fixture PayPal" }},
  {{ icon: createElement(ShieldCheck), label: "Attacks blocked", value: "{blocked} / {attacks}", delta: "red team", tone: "{'pos' if blocked == attacks else 'neg'}" as const, hint: "scripted attacks through the real checkout path" }},
  {{ icon: createElement(ListChecks), label: "Rules per cart", value: "{rules}", hint: "checks on an ordinary coffee cart, no model involved" }},
  {{ icon: createElement(Landmark), label: "PayPal endpoints", value: "{endpoints}", hint: "Orders, Payments, Disputes, Webhooks and OAuth calls in the client" }},
];
"""
    (ROOT / "frontend" / "src" / "landing" / "measured.ts").write_text(ts, encoding="utf-8")
    print(f"tests={n_tests} blocked={blocked}/{attacks} rules={rules} endpoints={endpoints}")


if __name__ == "__main__":
    main()
